CREATE TABLE IF NOT EXISTS foreign_flow (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    stock_code VARCHAR(10) NOT NULL,
    date DATE NOT NULL,
    foreign_buy_vol BIGINT DEFAULT 0,
    foreign_sell_vol BIGINT DEFAULT 0,
    foreign_buy_val BIGINT DEFAULT 0,
    foreign_sell_val BIGINT DEFAULT 0,
    UNIQUE KEY uk_stock_date (stock_code, date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

